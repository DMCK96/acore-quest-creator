  '',
  '## How the parts fit',
  'Make it with `new_entity`, set its `type` and look, and use `set_loot` for a chest. Readable ones have `pages` of text. To place it, add entries to its `spawns` with `upsert_entity`, taking each `guid` from `allocate_ids` with kind `gameobjectSpawn`. `add_spawn` places only objects that already exist in the database.',
  '',
  '## Fields',
  '- `entry` — its id; chosen for you. Do not change it.',
  '- `name` — what the player sees.',
  '- `type` — `questGiver`, `chest`, `generic`, `text` (a readable page), or `goober` (something you click).',
  '- `displayId`, `size` — its model and scale (1 = normal).',
  '- `spawns` — where it stands: `guid`, `map`, `x`, `y`, `z`, `o`, `rotation` (a quaternion x, y, z, w; copy it from a neighbour with `area_overview`).',
  '- `pages` — text pages for a `text` object.',
  '- `onlyDuringQuest` — a quest id the player must have in the log to use or loot it, or null.',
  '- `loot` — what a chest gives (see the loot guide).',
  '',
  '## Common mistakes',
  '- No model (`displayId` 0) or no name.',
  '- A readable object with no pages.',
