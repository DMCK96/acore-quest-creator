const ITEM = lines(
  '## What it is',
  'A new item for the project: a weapon, armour, trinket or quest item, with its quality, level, stats and effects. It is written as an `item_template` row when a patch is exported.',
  '',
  '## How the parts fit',
  'Make it with `new_entity`, then set `fields`. A quest item (`itemClass` 12, `bonding` `quest`) is the default. For a weapon or armour set `itemClass`, `subclass`, `inventoryType` and the stats. Name it in `check_names` first.',
  '',
  '## Fields',
  '- `entry` — its id; chosen for you. Do not change it.',
  '- `name`, `description` — the title and the flavour text.',
  '- `quality` — `poor`, `common`, `uncommon`, `rare`, `epic`, `legendary`, `artifact` or `heirloom`.',
  '- `itemClass`, `subclass`, `inventoryType` — what it is: class 2 weapon, 4 armour, 12 quest; the inventory type is the slot (13 one-hand, 17 two-hand, 14 shield).',
  '- `displayId` — its icon and model; copy one from an existing item with `entity_template`.',
  '- `itemLevel`, `requiredLevel` — its power and the level needed to use it.',
  '- `stackable`, `maxCount` — stack size and how many a player may own.',
  '- `bonding` — `none`, `pickup`, `equip`, `use` or `quest`.',
  '- `buyPrice`, `sellPrice` — in copper.',
  '- `startsQuest` — a quest id this item begins when used, or 0.',
  '- `armor`, `damage` (min, max, school), `delayMs` — armour value and weapon damage and speed.',
  '- `stats` — up to 10 `{ type, value }` pairs, `type` being the game\'s stat number.',
  '- `spells` — up to 5 effects: `spell`, `trigger` (when it fires), `charges`, `cooldownMs`.',
  '- `advanced` — any other `item_template` column, as text.',
  '',
  '## Common mistakes',
  '- A weapon with no `damage` or `delayMs`, or armour with `armor` 0.',
  '- A `legendary` item at a low `itemLevel`.',
  '- A `startsQuest` for a quest that does not exist.',
  '',
  '## What the editor checks',
  'Writing an item returns the editor\'s issues for it, such as `ITEM_NO_NAME`, `ITEM_NO_LOOK` (no look chosen), `ITEM_LEVELS`, `ITEM_STACK`, `ITEM_STARTS_UNKNOWN` (the quest it starts does not exist) and `ENTITY_TAKEN` (the entry already holds something in the database). A weapon an NPC cannot hold is reported on that NPC as `ENTITY_WEAPON`.',
);

const GUIDES: Record<AuthoringModel, string> = {
  scene: SCENE,
  fight: FIGHT,
  patrol: PATROL,
  loot: LOOT,
  npc: NPC,
  object: OBJECT,
  item: ITEM,
};

/** The guide for an authoring model: markdown, at most 6000 characters. */
export const guideOf = (model: AuthoringModel): string => GUIDES[model];
